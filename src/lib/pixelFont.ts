export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** One blank column between letters. */
export const GLYPH_SPACING = 1;

/** Width in pixels that `drawPixelText` will occupy. */
export function measurePixelText(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * (GLYPH_W + GLYPH_SPACING) - GLYPH_SPACING) * scale;
}

/**
 * Draws text on the pixel grid.
 *
 * `x`/`y` is the top-left corner unless `align` says otherwise. Unknown
 * characters render as a blank space, so a stray symbol never throws mid-frame.
 */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  align: 'left' | 'center' = 'left'
): void {
  const upper = text.toUpperCase();
  const startX = align === 'center' ? Math.round(x - measurePixelText(upper, scale) / 2) : Math.round(x);
  const top = Math.round(y);

  ctx.fillStyle = color;
  let cursor = startX;
  for (const char of upper) {
    const glyph = GLYPHS[char];
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row++) {
        const line = glyph[row];
        for (let col = 0; col < GLYPH_W; col++) {
          if (line[col] === '#') {
            ctx.fillRect(cursor + col * scale, top + row * scale, scale, scale);
          }
        }
      }
    }
    cursor += (GLYPH_W + GLYPH_SPACING) * scale;
  }
}

/** Same text drawn twice, offset, for a cheap drop shadow that stays on-grid. */
export function drawPixelTextShadowed(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  shadow = '#000000',
  scale = 1,
  align: 'left' | 'center' = 'left'
): void {
  drawPixelText(ctx, text, x + scale, y + scale, shadow, scale, align);
  drawPixelText(ctx, text, x, y, color, scale, align);
}
